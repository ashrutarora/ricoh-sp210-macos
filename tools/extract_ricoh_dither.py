"""extract_ricoh_dither.py rastertolilo > native/dither_ricoh.h

Reads the halftone table (symbol MapDitherTblMono, 256 x 24 x 3 bytes) out of your own copy of
Ricoh's Linux filter, for `make RICOH_DITHER=1` builds that match Ricoh's output byte for byte.
The table is Ricoh's, so the generated header is not part of this project and is git-ignored.

SPDX-License-Identifier: GPL-2.0-or-later
"""
import hashlib
import struct
import sys

SHA256 = "4d99ab2b66b674600d15bcea2dbb30da91f6bfd07dc8390f82f7dcefeb8465ab"  # SP-210211-series 0.03
SYMBOL = b"MapDitherTblMono"
SIZE = 256 * 24 * 3


def main():
    data = open(sys.argv[1], "rb").read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit(f"{sys.argv[1]}: not the rastertolilo this was written for (sha256 {SHA256})")

    # ELF32 little-endian: find the symbol in .symtab, then its bytes through its section
    shoff, = struct.unpack_from("<I", data, 0x20)
    shentsize, shnum, _ = struct.unpack_from("<HHH", data, 0x2e)
    sections = [struct.unpack_from("<10I", data, shoff + i * shentsize) for i in range(shnum)]
    symtab = next(s for s in sections if s[1] == 2)          # SHT_SYMTAB
    strtab = sections[symtab[6]]                             # sh_link
    for off in range(symtab[4], symtab[4] + symtab[5], 16):
        name, value, size, _, _, shndx = struct.unpack_from("<IIIBBH", data, off)
        end = data.index(b"\0", strtab[4] + name)
        if data[strtab[4] + name:end] == SYMBOL:
            sec = sections[shndx]
            start = sec[4] + value - sec[3]
            table = data[start:start + SIZE]
            break
    else:
        sys.exit("symbol MapDitherTblMono not found")

    print("/* Generated by tools/extract_ricoh_dither.py from Ricoh's rastertolilo. Not for distribution. */")
    print("static const unsigned char dither_patterns[256][24][3] = {")
    for g in range(256):
        rows = ",".join("{%s}" % ",".join("0x%02x" % b for b in table[g * 72 + r * 3:g * 72 + r * 3 + 3])
                        for r in range(24))
        print("  {%s}," % rows)
    print("};")


if __name__ == "__main__":
    main()
