"""make_dither.py > native/dither_own.h: this project's own halftone patterns.

A clustered-dot screen, as laser printers like: round dots on a 45-degree lattice with
spacing 3*sqrt(2) pixels (about 141 lines per inch at 600 dpi). The 24x24 cell holds 32 dots
of 18 pixels each. Each dot grows from its centre outwards; the 32 dots take turns in a
dispersed (Bayer) order, so the cell has 577 distinct tone steps. Grey level g (0 white,
255 black) blackens the first round(g * 576 / 255) pixels of that order.

Output format matches what the filter expects: patterns[256][24][3], bit 7 = leftmost pixel.
"""
import math

N = 24          # cell size in pixels
P = 6           # lattice period along each 45-degree diagonal


def dot_of(x, y):
    """Lattice dot that owns pixel (x, y): dot centres sit where u = x+y and v = x-y are
    multiples of P. Returns the dot's (u, v) centre and the pixel's offset from it."""
    u, v = x + y + 1, x - y              # coordinates of the pixel centre (x + .5, y + .5)
    cu, cv = P * math.floor(u / P + 0.5), P * math.floor(v / P + 0.5)
    centre = (((cu + cv) // 2) % N, ((cu - cv) // 2) % N)   # same dot across the cell's wrap
    return centre, (u - cu, v - cv)


def bayer(n):
    """n x n Bayer matrix (n a power of two)."""
    if n == 1:
        return [[0]]
    m = bayer(n // 2)
    return [[4 * m[y % (n // 2)][x % (n // 2)] + [[0, 2], [3, 1]][y // (n // 2)][x // (n // 2)]
             for x in range(n)] for y in range(n)]


def main():
    pixels = [(x, y) for y in range(N) for x in range(N)]
    dots = {}
    for x, y in pixels:
        centre, (du, dv) = dot_of(x, y)
        # spot function: distance from the dot centre, with a tiny angle term to break ties
        r = math.hypot(du, dv) + 1e-3 * ((math.atan2(dv, du) + math.pi) % (2 * math.pi))
        dots.setdefault(centre, []).append((r, x, y))
    assert len(dots) == 32 and all(len(p) == 18 for p in dots.values()), \
        sorted(len(p) for p in dots.values())

    # dispersed order for the dots themselves, from an 8x8 Bayer matrix on the dot centres
    b = bayer(8)
    centres = sorted(dots, key=lambda c: (b[(c[0] + c[1]) // P % 8][(c[0] - c[1]) // P % 8], c))
    order = []
    for k in range(18):                     # every dot gets its k-th pixel before any its k+1-th
        for c in centres:
            r, x, y = sorted(dots[c])[k]
            order.append((x, y))
    assert len(set(order)) == N * N

    rank = {p: i for i, p in enumerate(order)}
    print("/* Halftone patterns for rastertoricohsp210, generated by tools/make_dither.py.")
    print("   SPDX-License-Identifier: GPL-2.0-or-later */")
    print("static const unsigned char dither_patterns[256][24][3] = {")
    for g in range(256):
        n = round(g * N * N / 255)
        rows = []
        for y in range(N):
            bits = [1 if rank[(x, y)] < n else 0 for x in range(N)]
            rows.append("{%s}" % ",".join(
                "0x%02x" % int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, N, 8)))
        print("  {%s}," % ",".join(rows))
    print("};")


if __name__ == "__main__":
    main()
